def _rpc(proc, msg: dict) -> None:
    body = json.dumps(msg).encode()
    proc.stdin.write(f"Content-Length: {len(body)}\r\n\r\n".encode() + body)
    proc.stdin.flush()


def _reply(proc, want_id: int, limit: int = 40):
    """The response to `want_id`, skipping the server's notifications."""
    for _ in range(limit):
        length = 0
        while (line := proc.stdout.readline()) and line.strip():
            if line.lower().startswith(b"content-length:"):
                length = int(line.split(b":", 1)[1])
        if not length:
            return None
        msg = json.loads(proc.stdout.read(length))
        if msg.get("id") == want_id:
            return msg
    return None


def lsp() -> None:
    S.section("CLAUDE-LOCAL LSP BASELINE (REAL documentSymbol)")
    root = P.deployed_client_root() / "claude"
    env = json.loads((root / "settings.json").read_text()).get("env") or {}
    check("ENABLE_LSP_TOOL" not in env, "no obsolete ENABLE_LSP_TOOL gate in the local root")
    server = shutil.which("pyright-langserver")
    if not server:
        S.skip("pyright documentSymbol baseline", "pyright-langserver not installed (npm i -g pyright)")
        return
    # Plugin state is per config root; claude-local once shipped Python alone.
    out = run(["claude", "plugin", "list"], timeout=120, env={
        **os.environ, "CLAUDE_CONFIG_DIR": str(root)}).stdout if shutil.which("claude") else ""
    missing = [p for _l, p, binary, _c in C.LSP_PLUGINS
               if shutil.which(binary) and f"{p}@claude-plugins-official" not in out]
    check(out and not missing, "every LSP plugin whose server exists is in the local root", str(missing))
    probe = RESOURCES / "deploy/litellm/hooks/tool_gateway.py"
    proc = subprocess.Popen([server, "--stdio"], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=subprocess.DEVNULL)
    try:
        _rpc(proc, {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
            "processId": os.getpid(), "rootUri": REPO.as_uri(), "capabilities": {}}})
        check("result" in (_reply(proc, 1, 20) or {}), "pyright initializes")
        _rpc(proc, {"jsonrpc": "2.0", "method": "initialized", "params": {}})
        _rpc(proc, {"jsonrpc": "2.0", "method": "textDocument/didOpen", "params": {"textDocument": {
            "uri": probe.as_uri(), "languageId": "python", "version": 1, "text": probe.read_text()}}})
        _rpc(proc, {"jsonrpc": "2.0", "id": 2, "method": "textDocument/documentSymbol",
                    "params": {"textDocument": {"uri": probe.as_uri()}}})
        symbols = (_reply(proc, 2) or {}).get("result")
        names = [s.get("name") for s in symbols] if isinstance(symbols, list) else []
        check(bool(names), f"documentSymbol returns real symbols ({len(names)}: {names[:3]})")
    finally:
        proc.kill()


def rollback() -> None:
    S.section("GENERATION: MARKERS REQUIRED, ROLLBACK ON PARTIAL FAILURE")
    path = REPO / "src/ailocal/generation.py"
    sm = load_module("generation", path)
    got = "RETURNED"
    try:
        sm.splice("no markers here\n", "<<BEGIN>>", "<<END>>", "x", "model_list")
    except SystemExit as exc:
        got = str(exc)
    check("markers not found" in got, "a template with no markers aborts generation", got)
    dests = [sm.LITELLM_CONFIG, sm.CAPS_JSON, sm.CODEX_CATALOG, sm.CLAUDE_SETTINGS,
             sm.CODEX_CONFIG, sm.CONFIGURE_ZSH, sm.CONTRACT_JSON]

    def generate(fail_after=None) -> int:
        mod, calls, real = load_module("generation", path), [0], os.replace

        def flaky(src, dst):
            if not str(src).endswith(".bak-sync"):     # restores still run: an I/O error, not SIGKILL
                calls[0] += 1
                if fail_after is not None and calls[0] == fail_after + 1:
                    raise OSError("injected fault mid-replace")
            return real(src, dst)
        with patch.object(mod.os, "replace", flaky), contextlib.suppress(SystemExit, OSError):
            mod.main([])
        return calls[0]

    def digests():
        return [hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None for p in dests]
    generate()
    # Perturb generated files only, so every destination a clean run writes really changes.
    for p in dests:
        p.write_text(p.read_text() + ("\n" if p.suffix == ".json" else "\n# perturbed\n"))
    before = digests()
    n = generate(fail_after=3)
    mixed = [p.name for p, a, b in zip(dests, before, digests()) if a != b]
    check(n > 3 and not mixed, f"a fault after 3 of {n} replaces rolls every destination back",
          f"mixed: {mixed}")
    left = [str(f) for d in {p.parent for p in dests} for f in d.glob("*.*-sync")]
    check(not left, "no .tmp-sync/.bak-sync files survive a failure", str(left))
    generate()
    kept = [p.name for p, a, b in zip(dests, before, digests()) if a == b]
    check(not kept, "a clean run replaces every destination", f"unchanged: {kept}")


def main() -> int:
    for section in (targets, vscode, mcp, codex, drift, roles, instructions, lsp, rollback):
        try:
            section()
        except Exception as exc:  # noqa: BLE001
            S.error(section.__name__, exc)
    return S.report()


if __name__ == "__main__":
    sys.exit(main())
