def _configured(argv, present):
    order: list[str] = []
    with patch.dict(C._TARGETS, {n: (lambda n=n: order.append(n)) for n in C._TARGETS}), \
            patch.object(C, "present", lambda name: name in present), \
            patch.object(C, "_master_key", lambda: "sk-test"), \
            patch.object(C, "ensure_shell_sourcing", lambda key: None), \
            patch.object(C, "report_missing", lambda names: None), \
            patch.object(generation, "main", lambda argv: 0):
        return C.main(argv), order


def targets() -> None:
    S.section("TARGET SELECTION")
    with patch.object(generation, "main") as gen, patch.object(C, "ensure_shell_sourcing") as sh, \
            patch.object(C, "_master_key") as key, patch.object(C, "present", return_value=True), \
            patch.dict(C._TARGETS, {n: (lambda: check(False, "dry-run wrote client state"))
                                    for n in C.TARGETS}):
        check(C.main(["all", "--dry-run"]) == 0 and not (gen.called or sh.called or key.called),
              "dry-run skips generation, secrets, shell edits and client setup")
    for argv, present, rc, want, label in (
            (["all"], {"claude"}, 0, list(C.TARGETS), "`all` configures every supported client"),
            ([], {"claude", "codex"}, 0, ["claude", "codex"], "no argument: detected clients only"),
            (["codex"], set(), 0, ["codex"], "a named target is configured even when absent"),
            (["nope"], {"claude"}, 1, [], "an unknown target fails and configures nothing"),
            ([], set(), 0, [], "nothing detected, no argument: clean exit")):
        got_rc, order = _configured(argv, present)
        check(got_rc == rc and sorted(order) == sorted(want), label, f"rc={got_rc} order={order}")


def _vscode(user_dir, which_code: bool, writes_fail: bool = False) -> int:
    boom = Mock(side_effect=OSError(13, "Permission denied"))
    with patch.multiple(C, _vscode_user_dir=lambda: user_dir,
                        _code=lambda *a: "1.99.0\nabc\nx64" if which_code else None,
                        _provider_group=boom if writes_fail else (lambda p, dry: None),
                        _prune_deprecated=lambda p, dry: None, _ensure_recommended=lambda p: None,
                        provision_vscode_research=lambda p: True,
                        provision_vscode_agent=lambda p: True, provision_copilot_mcp=lambda: True,
                        native_vscode_available=lambda: True), \
            patch.object(C.shutil, "which", lambda n: "/usr/local/bin/code" if which_code else None):
        return C.install_vscode([])


def vscode() -> None:
    S.section("VS CODE PRESENCE AND OUTCOMES")
    with patch.object(C, "_vscode_user_dir", lambda: Path("/leftover/Code/User")):
        for app, which, want, label in (
                (None, None, False, "leftover settings with no app or CLI are absent"),
                (Path("/Applications/Visual Studio Code.app"), None, True, "an app bundle is present"),
                (None, "/usr/local/bin/code", True, "the code CLI alone is present")):
            with patch.object(C, "_vscode_app", lambda: app), \
                    patch.object(C.shutil, "which", lambda n: which if n == "code" else None):
                check(C.present("vscode") is want, label)
    with temp_dir() as box:
        empty = box / "Applications" / "Visual Studio Code.app"
        empty.mkdir(parents=True)
        with patch.object(Path, "home", classmethod(lambda cls: box)):
            check(C._vscode_app() != empty, "an emptied .app directory is not a bundle")
    tmp = Path("/tmp/does-not-need-to-exist")
    # Collapsing a write failure into absence silently dropped the Copilot instructions.
    for args, want, label in (((tmp, True), C.VSCODE_OK, "success"),
                              ((None, False), C.VSCODE_ABSENT, "not installed"),
                              ((None, True), C.VSCODE_ABSENT, "installed, never launched"),
                              ((tmp, True, True), C.VSCODE_FAILED, "write failure is not absence")):
        got = _vscode(*args)
        check(got == want, f"install_vscode: {label}", f"got {got}")
    for outcome, want in ((C.VSCODE_OK, True), (C.VSCODE_ABSENT, False), (C.VSCODE_FAILED, False)):
        seen: list = []
        with patch.object(C, "install_vscode", lambda argv: outcome), \
                patch.object(C, "_copilot_instructions", lambda: seen.append(1)):
            C.target_vscode()
        check(bool(seen) is want, f"Copilot instructions deployed only on success (outcome {outcome})")

    S.section("VS CODE NATIVE MODEL PROVIDER")
    for tier in P.TIERS:
        models = generation.load_models_yaml(P.profile_path(tier, RESOURCES))
        foreign = {"vendor": "customendpoint", "name": "Other endpoint", "models": []}
        old = {"vendor": "litellm-connector", "name": "LiteLLM", "baseUrl": C.BASE_URL, "apiKey": "${k}"}
        group = (result := C.vscode_provider_document([foreign, old], models))[-1]
        chat = [r for r in models if r != "completion"]
        check(result[0] == foreign and group["apiKey"] == old["apiKey"]
              and C.vscode_provider_document(result, models) == result,
              f"{tier}: migration keeps foreign providers and the secret reference; idempotent")
        check([x["id"] for x in group["models"]] == ["ailocal-" + r for r in chat]
              and all(x["maxInputTokens"] == models[x["id"][8:]]["context_input"]
                      and x["maxOutputTokens"] == models[x["id"][8:]]["max_output"]
                      and x["vision"] for x in group["models"]),
              f"{tier}: every chat alias (no FIM) with real limits and vision")
        changed = {**models["architecture"], "active": "unqualified-model", "guidance": {}}
        guidance = C.copilot_model_guidance(models)
        check(not C.vscode_provider_document([], {"architecture": changed})[-1]["models"][0]["vision"]
              and all("ailocal-" + r in guidance and models[r]["guidance"]["prompting"][0] in guidance
                      for r in chat),
              f"{tier}: an unqualified model gets no vision; Copilot guidance needs no MCP")
    stranger = {"vendor": "litellm-connector", "name": "LiteLLM", "baseUrl": "http://10.0.0.5:4000"}
    check(C.vscode_provider_document([stranger], models)[0] == stranger,
          "a connector group aimed at another proxy is foreign and preserved")
    with contextlib.suppress(ValueError):
        C.vscode_provider_document({"bad": True}, models)
        check(False, "invalid provider file fails closed")
    with temp_dir() as user, patch.object(C, "_vscode_user_dir", lambda: user):
        target = user / "chatLanguageModels.json"
        for text, want, label in (
                ("[", None, "unparseable"),
                (json.dumps([7, {"vendor": C.VSCODE_VENDOR, "name": C.VSCODE_PROVIDER_NAME}]),
                 None, "non-object entry"),
                (json.dumps([stranger]), False, "foreign-only")):
            target.write_text(text)
            with patch.dict(generation._STAGE, clear=True), \
                    patch.dict(generation._STAGED_TEXT, clear=True):
                got = generation.regen_vscode(models)
                check(got is want and target.read_text() == text and target not in generation._STAGE,
                      f"start preserves a {label} VS Code model file and does not abort")


def _native_mcp(calls: list):
    """Stand-in for `claude mcp` / `codex mcp`, writing only where CLAUDE_CONFIG_DIR/CODEX_HOME point."""
    def fake(command, **kwargs):
        var = "CLAUDE_CONFIG_DIR" if command[0] == "claude" else "CODEX_HOME"
        calls.append((command, kwargs["env"][var]))
        root = Path(kwargs["env"][var])
        if command[0] == "claude":
            path = root / ".claude.json"
            data = json.loads(path.read_text()) if path.exists() else {}
            servers = data.setdefault("mcpServers", {})
            if command[2] == "remove":
                servers.pop(command[-1])
            else:
                servers[command[-2]] = json.loads(command[-1])
            path.write_text(json.dumps(data, indent=2))
        else:
            path = root / "config.toml"
            body = path.read_text() if path.exists() else ""
            if command[2] == "remove":
                body = re.sub(rf"(?ms)^\[mcp_servers\.{re.escape(command[3])}\][^\n]*\n(?:(?!^\[).*?\n)*",
                              "", body)
            else:
                sep = command.index("--")
                body += (f'\n[mcp_servers.{command[3]}]\ncommand = "{command[sep + 1]}"\n'
                         f"args = {json.dumps(command[sep + 2:])}\n")
            path.write_text(body)
        return SimpleNamespace(returncode=0)
    return fake


def mcp() -> None:
    S.section("COPILOT PORTABLE MCP")
    with temp_dir() as box:
        path = box / "mcp-config.json"
        agent = {"command": "/old/ailocal", "args": ["mcp", "agent"], "timeout": 123}
        path.write_text(json.dumps({"version": 1, "mcpServers": {"foreign": {"x": 1}, "agent": agent}}))
        path.chmod(0o600)
        with patch.object(C.policy, "client_mcp_path", return_value=path), \
                patch.object(C.shutil, "which", return_value="/new/ailocal"):
            ok = C.provision_copilot_mcp()
            data = json.loads(path.read_text())
            check(ok and path.stat().st_mode & 0o777 == 0o600 and data["version"] == 1
                  and data["mcpServers"]["foreign"] == {"x": 1}
                  and data["mcpServers"]["agent"] == {**agent, "command": "/new/ailocal"}
                  and data["mcpServers"]["research"]["args"] == ["mcp", "research"],
                  "registers both servers; keeps foreign entries, options and 0600")
            check(C.provision_copilot_mcp() and json.loads(path.read_text()) == data, "idempotent")
            data["mcpServers"]["research"] = {"command": "foreign"}
            for text, label in ((json.dumps(data), "same-name collision"), ("{invalid", "invalid JSON")):
                path.write_text(text)
                check(not C.provision_copilot_mcp() and path.read_text() == text,
                      f"{label} fails and preserves the file")

    # ailocal once registered local-agent in the HOSTED roots, which outlived its uninstall.
    S.section("AGENT MCP: LOCAL ROOTS ONLY, HOSTED BYTE-IDENTICAL")
    with temp_dir() as root:
        hosted, local = root / "hosted", root / "local"
        for d in (hosted, local / "claude", local / "codex"):
            d.mkdir(parents=True)
        ours = {"type": "stdio", "command": "ailocal", "args": ["mcp", "agent"], "env": {}}
        (hosted / ".claude.json").write_text(json.dumps({"mcpServers": {"local-agent": ours}}))
        (hosted / "config.toml").write_text(
            'model = "keep"\n[mcp_servers.local-agent] # managed by cadence - x\n'
            'command = "ailocal"\nargs = ["mcp", "agent"]\n')
        cl, cx = local / "claude/.claude.json", local / "codex/config.toml"
        cl.write_text(json.dumps({"session": "keep", "mcpServers": {
            "foreign": {"command": "keep"}, "local-agent": ours}}))
        cx.write_text('# Generated by ailocal. Do not edit.\nmodel = "ailocal-implementation"\n'
                      '[mcp_servers.foreign]\ncommand = "keep"\n'
                      '[mcp_servers.local-agent]\ncommand = "/opt/bin/ailocal"\nargs = ["mcp", "agent"]\n')
        before = {p: p.read_bytes() for p in hosted.iterdir()}
        calls: list = []
        with patch.dict(os.environ, {"CODEX_HOME": str(hosted), "CLAUDE_CONFIG_DIR": str(hosted)}), \
                patch.object(C.policy, "deployed_client_root", return_value=local), \
                patch.object(C, "present", return_value=True), \
                patch.object(C, "provision_mcp_runtime", return_value=root / "py"), \
                patch.object(C.subprocess, "run", side_effect=_native_mcp(calls)):
            check(C.provision_local_agent(), "agent MCP provisioned for claude and codex")
            for name, got in (("claude", json.loads(cl.read_text())["mcpServers"]),
                              ("codex", tomllib.loads(cx.read_text())["mcp_servers"])):
                a = got.get(C.AGENT_MCP, {})
                check(Path(a.get("command", "")).name == "ailocal" and a.get("args") == ["mcp", "agent"]
                      and C.LEGACY_AGENT_MCP not in got and got.get("foreign") == {"command": "keep"},
                      f"{name}-local: `{C.AGENT_MCP}` registered, legacy retired, foreign kept")
            check(json.loads(cl.read_text())["session"] == "keep"
                  and tomllib.loads(cx.read_text())["model"] == "ailocal-implementation",
                  "local session and model settings survive")
            check(all(p.read_bytes() == b for p, b in before.items()), "hosted roots are byte-identical")
            check(calls and all(w == str(local / c[0]) for c, w in calls)
                  and not any(c[2] in ("add", "add-json") and C.LEGACY_AGENT_MCP in c for c, _ in calls),
                  "every native call targets a local root; nothing under the hosted alias",
                  str([w for _, w in calls]))
            snapshot, n = {p: p.read_bytes() for p in (cl, cx)}, len(calls)
            check(C.provision_local_agent() and len(calls) == n
                  and all(p.read_bytes() == b for p, b in snapshot.items()),
                  "reinstall makes no native call and changes nothing")
            data = json.loads(cl.read_text())
            data["mcpServers"][C.AGENT_MCP] = {"command": "operator-server"}
            data["mcpServers"][C.LEGACY_AGENT_MCP] = {"command": "operator-local-agent"}
            cl.write_text(json.dumps(data))
            ok = C.provision_local_agent(["claude"])
            check(not ok and json.loads(cl.read_text()) == data,
                  "a foreign `agent` server fails the install and is left untouched")
        shutil.rmtree(local)
        check(all(p.read_bytes() == b for p, b in before.items()),
              "uninstall (deleting ailocal's roots) leaves hosted roots as seeded")

    S.section("CODEX ROOT: NO INSTRUCTION FILE; A PRIOR RENDERING IS RETIRED ONLY BY DIGEST")
    with temp_dir() as box:
        local, mine = box / "local", "# ailocal local runtime\nrendered by a previous ailocal\n"
        (agents := local / "codex" / "AGENTS.md").parent.mkdir(parents=True)
        agents.write_text(mine)
        with patch.object(C, "RETIRED_CODEX_INSTRUCTIONS",
                          frozenset({hashlib.sha256(mine.encode()).hexdigest()})), \
                patch.object(C.policy, "deployed_client_root", return_value=local), \
                patch.object(C, "provision_mcp_runtime", return_value=None):
            C.target_codex()
            check(not agents.exists(), "a byte-identical prior rendering is retired")
            agents.write_text(mine + "edit\n")
            C.target_codex()
            check(agents.read_text() == mine + "edit\n", "an edited or composed AGENTS.md is kept")
            agents.unlink()
            (elsewhere := box / "elsewhere.md").write_text(mine)
            agents.symlink_to(elsewhere)
            C.target_codex()
            check(agents.is_symlink() and elsewhere.read_text() == mine,
                  "a symlinked AGENTS.md is never removed or written through")


def codex() -> None:
    S.section("STATUS: CODEX LINE REPORTS REGISTRATIONS (#43)")
    with temp_dir() as tmp:
        cfg = tmp / "config.toml"
        check(runtime.codex_status(cfg) == "", "absent config: not installed")
        servers = '[mcp_servers.research]\ncommand = "a"\n[mcp_servers.agent]\ncommand = "a"\n'
        for body, want, label in ((servers, ("agent, research", "not probed"), "servers named, unprobed"),
                                  ('model = "m"\n', ("no MCP servers",), "no registration stated"),
                                  ("[mcp_servers\n", ("unreadable",), "malformed config reported")):
            cfg.write_text(body)
            line = runtime.codex_status(cfg)
            check(all(w in line for w in want) and "NOT reachable" not in line, label, line)

    # Dropping [hooks.state] re-armed "Hooks need review" after every `ailocal start`.
    S.section("CODEX CONFIG.TOML: CO-OWNED RECORDS SURVIVE REGENERATION")
    T = 'model = "ailocal-implementation"\n\n[model_providers.ailocal]\nname = "x"\n'
    HOOK = '[hooks.state."/x/codex/config.toml:session_start:0:0"]\ntrusted_hash = "sha256:6ef5bb"\n'
    PROJ = '[projects."/x/repo"]\ntrust_level = "trusted"\n'
    TUI = "[tui]\nscreen_reader_detection_done = true\n"
    with temp_dir() as td, patch.object(generation, "CODEX_CONFIG", td / "config.toml") as live:
        keep = generation._keep_codex_projects

        def merged(text, tpl=T):
            live.write_text(text)
            return keep(tpl)
        check(keep(T) == T, "no live file: the template is returned unchanged")
        out = merged(T + "\n" + PROJ + "\n[hooks.state]\n\n" + HOOK)
        check(PROJ in out and HOOK in out and out.count("[model_providers.ailocal]") == 1,
              "project and hook trust records survive; owned tables are not duplicated")
        out = merged(T + "stale_hand_edit = true\n\n" + HOOK)
        check("stale_hand_edit" not in out and merged(out, out) == out,
              "only trust records are carried over, as a fixed point")
        out = merged(T + "\n" + HOOK + '\n[tui]\ntheme = "hand-edit"\nscreen_reader_detection_done = true\n')
        check(TUI in out and "hand-edit" not in out and out.count("[tui]") == 1
              and merged(out) == out and "screen_reader" not in keep(T + "\n[tui]\n"),
              "the screen-reader flag alone survives, in one [tui] table, as a fixed point")
        # A DOTALL `.*` once captured the rest of the file, writing later tables twice.
        out = merged(T + "\n" + TUI + "\n" + HOOK + "\n# ── Model Providers ──\n")
        check(out.count("[hooks.state.") == 1 and "Model Providers" not in out
              and tomllib.loads(out)["tui"] == {"screen_reader_detection_done": True},
              "a table after [tui] is carried once, without the next table's comment")
        check(merged(T + "\n" + HOOK + "\n" + HOOK).count("[hooks.state.") == 1,
              "a record held twice is repaired, not carried")
        tpl = T + '\n[mcp_servers.research]\ncommand = "ailocal"\n'
        out = merged(T + '\n[mcp_servers.research]\ncommand = "stale"\n'
                     '\n[mcp_servers.grepai] # managed by external registrar\ncommand = "grepai"\n'
                     'args = ["mcp-serve", "--workspace", "cadence"]\n'
                     '\n[mcp_servers.grepai.env]\nEXAMPLE = "value"\n'
                     '\n[mcp_servers."server.with.dots"]\ncommand = "other"\n', tpl)
        servers = tomllib.loads(out)["mcp_servers"]
        check(servers["grepai"] == {"command": "grepai", "args": ["mcp-serve", "--workspace", "cadence"],
                                    "env": {"EXAMPLE": "value"}}
              and servers["server.with.dots"] == {"command": "other"},
              "external MCP registrations (nested, quoted names) survive")
        check(servers["research"] == {"command": "ailocal"} and merged(out, tpl) == out,
              "the template owns its own server; preservation is a fixed point")
        PLUG = ('[marketplaces.cadence]\nsource_type = "local"\nsource = "/x/cadence-plugin"\n\n'
                '[plugins."cadence@cadence"]\nenabled = true\n')
        out = merged(T + "\n" + PLUG)
        check(tomllib.loads(out)["plugins"] == {"cadence@cadence": {"enabled": True}}
              and "[marketplaces.cadence]" in out and merged(out, out) == out,
              "codex plugin registrations survive, as a fixed point")

    S.section("CODEX GENERATED CONFIG")
    template = (CLIENTS_RES / "codex/config.template.toml").read_text(encoding="utf-8")
    disabled = set(re.findall(r'skills/\.system/([^/]+)/SKILL\.md"\nenabled = false', template))
    bundled = P.deployed_client_root() / "codex" / "skills" / ".system"
    installed = ({p.name for p in bundled.iterdir() if (p / "SKILL.md").is_file()}
                 if bundled.is_dir() else disabled)     # no installed Codex: nothing to compare
    check(disabled and disabled == installed, "the .system disable list matches the installed skills",
          f"disabled {sorted(disabled)}, installed {sorted(installed)}")
    gen = (P.deployed_client_root() / "codex" / "config.toml").read_text()
    n = len(re.findall(r"(?m)^\[mcp_servers\.research\]", gen))
    check(n == 1, "generated codex config declares research exactly once", f"found {n}")
    # An unconditional `cadence mcp sync` once re-applied global registrations to Codex.
    sync = [str(p.relative_to(REPO)) for p in (REPO / "src/ailocal").rglob("*.py")
            if re.search(r"(?m)^[^#\n]*cadence\s+mcp\s+sync", p.read_text())]
    check(not sync, "no ailocal source invokes `cadence mcp sync`", str(sync))
    compat = json.loads((P.deployed_client_root() / "integration-contract.json").read_text())[
        "compatibility"]
    cx, lsp = compat["codex_mcp_lsp"], compat["claude_native_lsp"]
    check(cx["configured"] is False and cx["execution"] == "not_configured"
          and not re.search(r"(?m)^\[mcp_servers\.lsp", template),
          "contract and template agree: no Codex LSP bridge", str(cx))
    # Cadence's vocabulary is fixed; any other value degrades to "configured, unverified".
    check(lsp["execution"] == "working" and (REPO / lsp.get("verified_by", "-")).is_file(),
          "claude_native_lsp is `working` and names a real verifier", str(lsp))


def drift() -> None:
    # Claude Code re-serialises settings.json; a byte compare reported drift on key order alone.
    S.section("--check: CO-OWNER ORDER IS NOT DRIFT")
    models = generation.load_models_yaml(generation.profile_path(tier=generation.resolve_tier(None)))
    with patch.dict(generation._STAGE, clear=True), patch.dict(generation._STAGED_TEXT, clear=True):
        generation.regen_claude_settings(models, generation.load_clients_yaml())
        staged = [t for p, t in generation._STAGED_TEXT.items() if p.name == "settings.json"]
    (text,) = staged     # exactly one settings.json is staged
    doc = json.loads(text)
    reordered = json.dumps({**{k: v for k, v in doc.items() if k != "//"},
                            **{k: v for k, v in doc.items() if k == "//"}}, indent=2) + "\n"
    server = '[mcp_servers.docs]\nurl = "https://docs.invalid/mcp"\n'
    toml = 'model = "ailocal-fast"\n\n[tui]\nx = 1\n\n' + server
    with temp_dir() as td:
        for name, want, live, label in (
                ("settings.json", text, text, True), ("settings.json", text, reordered, True),
                ("settings.json", text, json.dumps({**doc, "model": "x"}, indent=2), False),
                ("settings.json", text, "{not json", False),
                ("config.toml", toml, 'model = "ailocal-fast"\n\n' + server + "\n[tui]\nx = 1\n", True),
                ("config.toml", toml, toml.replace("ailocal-fast", "ailocal-review"), False),
                ("config.toml", toml, "[unclosed\n", False)):
            (td / name).write_text(live)
            check(generation._same(td / name, want) is label,
                  f"{name}: {'in sync' if label else 'drift'} for {live[:24]!r}")


def roles() -> None:
    S.section("CLAUDE-LOCAL ROLE OVERRIDES AND WORKFLOW TOGGLE")
    configure = P.deployed_client_root() / "configure.zsh"
    with temp_dir() as stub:
        (stub / "claude").write_text("#!/bin/sh\n" + "".join(
            f'echo "{v}=$ANTHROPIC_DEFAULT_{v}_MODEL"\n' for v in ("OPUS", "SONNET", "HAIKU", "FABLE"))
            + 'echo "WORKFLOWS=$CLAUDE_CODE_DISABLE_WORKFLOWS"\necho "ARGS=$*"\n')
        (stub / "claude").chmod(0o755)
        base = {k: v for k, v in os.environ.items() if not k.endswith("_ALIAS_OVERRIDE")
                and k != "AILOCAL_NATIVE_WORKFLOWS"}
