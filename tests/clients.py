def drift() -> None:
    # Claude Code re-serialises settings.json; a byte compare reported drift on key order alone.
    S.section("--check: CO-OWNER ORDER IS NOT DRIFT")
    models = generation.load_models_yaml(generation.profile_path(tier=generation.resolve_tier(None)))
    with patch.dict(generation._STAGE, clear=True), patch.dict(generation._STAGED_TEXT, clear=True):
        generation.regen_claude_settings(models, generation.load_clients_yaml())
        (text,) = [t for p, t in generation._STAGED_TEXT.items() if p.name == "settings.json"]
    doc = json.loads(text)
    reordered = json.dumps({**{k: v for k, v in doc.items() if k != "//"},
                            **{k: v for k, v in doc.items() if k == "//"}}, indent=2) + "\n"
    server = '[mcp_servers.docs]\nurl = "https://docs.invalid/mcp"\n'
    toml = 'model = "ailocal-fast"\n\n[tui]\nx = 1\n\n' + server
    cases = {"settings: identical": ("settings.json", text, text, True),
             "settings: reordered": ("settings.json", text, reordered, True),
             "settings: changed value": ("settings.json", text, json.dumps({**doc, "model": "x"}, indent=2), False),
             "settings: unparseable": ("settings.json", text, "{not json", False),
             "toml: reordered": ("config.toml", toml, 'model = "ailocal-fast"\n\n' + server + "\n[tui]\nx = 1\n", True),
             "toml: changed value": ("config.toml", toml, toml.replace("ailocal-fast", "ailocal-primary"), False),
             "toml: unparseable": ("config.toml", toml, "[unclosed\n", False)}
    wrong = []
    with temp_dir() as td:
        for label, (name, want, live, same) in cases.items():
            (td / name).write_text(live)
            if generation._same(td / name, want) is not same:
                wrong.append(label)
    check(not wrong, "--check reports drift on a changed or unparseable value, never on key or table order",
          str(wrong))


def roles() -> None:
    S.section("CLAUDE-LOCAL ROLE OVERRIDE")
    configure = P.deployed_client_root() / "configure.zsh"
    with temp_dir() as stub:
        (stub / "claude").write_text("#!/bin/sh\n" + "".join(
            f'echo "{v}=$ANTHROPIC_DEFAULT_{v}_MODEL"\n' for v in ("OPUS", "SONNET", "HAIKU", "FABLE"))
            + 'echo "ARGS=$*"\n')
        (stub / "claude").chmod(0o755)
        # The override check fetches the proxy's catalogue; a stopped stack must not fail
        # the gate, so /v1/models is answered here and everything else reaches real curl.
        real_curl = shutil.which("curl") or "/usr/bin/curl"
        catalogue = json.dumps({"data": [{"id": "ailocal-" + r} for r in ("primary", "fast", "cyber")]})
        (stub / "curl").write_text(f"#!/bin/sh\ncase \"$*\" in *'/v1/models'*) echo '{catalogue}'; exit 0;; esac\n"
                                   f'exec "{real_curl}" "$@"\n')
        (stub / "curl").chmod(0o755)
        base = {k: v for k, v in os.environ.items() if not k.endswith("_ALIAS_OVERRIDE")}
        base["PATH"] = f"{stub}{os.pathsep}{base['PATH']}"

        def launch(**env):
            r = run(["zsh", "-c", f"source '{configure}' >/dev/null 2>&1; claude-local --dry"],
                    env={**base, **env})
            got = dict(line.split("=", 1) for line in r.stdout.splitlines() if "=" in line)
            return r.returncode, got, r.stdout + r.stderr
        # settings.json `model` outranks ANTHROPIC_DEFAULT_*, so the override must pass --model.
        # The override is named by ROLE: every slot routed to primary follows it.
        _, defaults, _ = launch()
        rc, got, out = launch(AILOCAL_PRIMARY_ALIAS_OVERRIDE="ailocal-cyber")
        moved = {k: "ailocal-cyber" for k, v in defaults.items() if v == "ailocal-primary"}
        valid = rc == 0 and moved and got == {**defaults, **moved, "ARGS": "--model ailocal-cyber --dry"}
        rc, bad, out2 = launch(AILOCAL_PRIMARY_ALIAS_OVERRIDE="bench-does-not-exist")
        check(valid and rc != 0 and "OPUS" not in bad and "not served by LiteLLM" in out2,
              "a primary override reaches every primary slot and --model; an unserved one fails before launch",
              out + out2)


def rollback() -> None:
    S.section("GENERATION: ROLLBACK ON PARTIAL FAILURE")
    path = REPO / "src/ailocal/generation.py"
    sm = load_module("generation", path)
    dests = [sm.LITELLM_CONFIG, sm.CAPS_JSON, sm.CODEX_CATALOG, sm.CLAUDE_SETTINGS,
             sm.CODEX_CONFIG, sm.CONFIGURE_ZSH, sm.CONTRACT_JSON]

    def generate(fail_after=None) -> int:
        mod, calls, real = load_module("generation", path), [0], os.replace

        def flaky(src, dst):
            if not str(src).endswith(".bak-sync"):     # restores still run: an I/O error, not SIGKILL
                calls[0] += 1
                if fail_after is not None and calls[0] == fail_after + 1:
                    raise OSError("injected fault mid-replace")
            return real(src, dst)
        with patch.object(mod.os, "replace", flaky), contextlib.suppress(SystemExit, OSError):
            mod.main([])
        return calls[0]

    def digests():
        return [hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None for p in dests]
    generate()
    # Perturb generated files only, so every destination a clean run writes really changes.
    for p in dests:
        p.write_text(p.read_text() + ("\n" if p.suffix == ".json" else "\n# perturbed\n"))
    before = digests()
    n = generate(fail_after=3)
    mixed = [p.name for p, a, b in zip(dests, before, digests()) if a != b]
    left = [str(f) for d in {p.parent for p in dests} for f in d.glob("*.*-sync")]
    generate()
    check(n > 3 and not mixed and not left,
          f"a fault after 3 of {n} replaces rolls every destination back and leaves no temp files",
          f"mixed: {mixed}; left: {left}")


