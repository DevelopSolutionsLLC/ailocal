def _configured(argv, present):
    order: list[str] = []
    with patch.dict(C._TARGETS, {n: (lambda n=n: order.append(n)) for n in C._TARGETS}), \
            patch.object(C, "present", lambda name: name in present), \
            patch.object(C, "_master_key", lambda: "sk-test"), \
            patch.object(C, "ensure_shell_sourcing", lambda: None), \
            patch.object(C, "report_missing", lambda names: None), \
            patch.object(generation, "main", lambda argv: 0):
        return C.main(argv), order


def targets() -> None:
    S.section("TARGET SELECTION")
    want = {"all": (0, sorted(C.TARGETS)), "detected": (0, ["claude", "codex"]), "named absent": (0, ["codex"]),
            "unknown": (1, []), "none detected": (0, [])}
    got = {}
    for label, argv, present in (("all", ["all"], {"claude"}), ("detected", [], {"claude", "codex"}),
                                 ("named absent", ["codex"], set()), ("unknown", ["nope"], {"claude"}),
                                 ("none detected", [], set())):
        rc, order = _configured(argv, present)
        got[label] = (rc, sorted(order))
    check(got == want, "clients configures exactly the selected targets; an unknown target configures nothing",
          str(got))


