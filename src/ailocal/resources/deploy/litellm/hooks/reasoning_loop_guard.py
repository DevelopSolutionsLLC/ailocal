"""reasoning_loop_guard.py — retry once a /v1/responses turn that loops or delivers nothing.

DEFECT    In a tool-calling turn a Gemma 4 backend can stop converging: it holds the
          answer, then reasons "Final answer. … Actually, I'll check …" until
          num_predict, and Codex fails the turn with `Incomplete response returned,
          reason: max_output_tokens`. Measured on gemma4:26b-qat-mtp: 2 of 13
          real codex-local sessions, 700-850 s each, no answer (#68).
CAUSE     The replayed reasoning items. On a captured looping request, dropping
          them gave the correct answer 5/5; thinking off, temperature 0.6, and
          keeping the last 1 or 3 items did not. Matches the in-turn re-injection
          loop reported for Gemma 4 (huggingface.co/google/gemma-4-12B-it,
          discussion 38).
WHY NOT ALWAYS DROP  Dropping them on every request removed the loop (0/8) but cut
          accuracy to 3/8: the model loses the record of what it already
          checked. Google's Gemma 4 format keeps thoughts between function calls,
          and #38 relies on replay for Qwen. So replay stays, and only a turn
          that is already looping is re-sent without it.
FIX       Hold the stream while it carries only reasoning. On the first answer or
          tool-call event, release everything held and pass the rest through
          unchanged. Past the registry's `reasoning_chars`, or on an incomplete
          reasoning-only end, stop reading, re-send the same request once
          without reasoning items, and stream that instead. Nothing held has
          reached the client, so it sees exactly one response.
SCOPE     /v1/responses requests for backends the registry's
          `reasoning_loop_guard` names; the reasoning threshold applies only to
          requests that carry replayed reasoning. Everything else passes
          through untouched.
COST      A normal step is delayed by its reasoning (it is released with the
          first answer event; Codex shows nothing during reasoning either way).
          A caught loop costs the threshold's tokens plus one retry, instead of
          num_predict and a failed turn.
RETIRE    When a captured looping request no longer loops with this hook removed.

DEFECT 2  A Gemma 4 turn can complete with only reasoning: Ollama's gemma4 parser
          fails on the tool call, discards it, and logs only `gemma4 tool call
          parsing failed` (the model wrote `content:*** Begin Patch…<|"|>}`,
          missing the opening string delimiter). Codex then ends the turn
          without the edit. Measured on gemma4:26b-qat-mtp, Ollama 0.40.14: 4 of 9
          codex-local edit runs (#69). The text never leaves Ollama, so the
          proxy cannot repair it.
FIX 2     A guarded request whose stream completes while still reasoning-only is
          re-sent once, unchanged; replays of a captured instance produced the
          call or the patch 3/3. This applies with or without replayed
          reasoning, since the first edit request of a turn carries none.
RETIRE 2  When Ollama's gemma4 parser accepts a string value with no opening
          delimiter, or reports the failure to the client.
"""
import copy
import logging
import os

from litellm.integrations.custom_logger import CustomLogger

log = logging.getLogger("ailocal.reasoning_loop_guard")


def _load_registry_module():
    """Import the sibling capability_registry.py by path (see tool_gateway.py:
    LiteLLM's file loader puts no hooks directory on sys.path)."""
    import importlib.util
    import sys as _sys
    if "capability_registry" in _sys.modules:
        return _sys.modules["capability_registry"]
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "capability_registry.py")
    spec = importlib.util.spec_from_file_location("capability_registry", path)
    module = importlib.util.module_from_spec(spec)
    _sys.modules["capability_registry"] = module
    spec.loader.exec_module(module)
    return module


#: Request fields re-sent on a retry. Proxy bookkeeping (logging objects, call IDs,
#: auth metadata) is not a Responses parameter and is regenerated by the router.
RESPONSES_FIELDS = ("model", "input", "instructions", "tools", "tool_choice",
                    "parallel_tool_calls", "reasoning", "include", "store",
                    "max_output_tokens", "temperature", "top_p", "text",
                    "truncation", "prompt_cache_key", "user")


def _get(obj, name):
    return obj.get(name) if isinstance(obj, dict) else getattr(obj, name, None)


def _event_type(chunk):
    t = _get(chunk, "type")
    return getattr(t, "value", t) or ""


def _is_reasoning_delta(t):
    return t.startswith("response.reasoning") and t.endswith(".delta")


def _is_answer(chunk, t):
    """An event that starts or carries visible output or a tool call."""
    if t.startswith(("response.output_text", "response.function_call",
                     "response.content_part", "response.refusal")):
        return True
    if t.startswith("response.output_item"):
        item_type = _get(_get(chunk, "item") or {}, "type")
        return item_type not in (None, "reasoning")
    return False


def _replayed_reasoning(data):
    items = data.get("input") if isinstance(data, dict) else None
    if not isinstance(items, list):
        return 0
    return sum(1 for i in items if isinstance(i, dict) and i.get("type") == "reasoning")


def resend(data, drop_reasoning=True):
    """The request's Responses fields, with every replayed reasoning item removed
    when `drop_reasoning`."""
    retry = {k: copy.deepcopy(data[k]) for k in RESPONSES_FIELDS if k in data}
    if drop_reasoning:
        retry["input"] = [i for i in retry.get("input") or []
                          if not (isinstance(i, dict) and i.get("type") == "reasoning")]
    retry["stream"] = True
    return retry


async def _router_retry(data):
    from litellm.proxy.proxy_server import llm_router
    return await llm_router.aresponses(**data)


class ReasoningLoopGuard(CustomLogger):
    def __init__(self, registry=None, retry=None):
        super().__init__()
        self._registry = registry
        self._retry = retry or _router_retry

    @property
    def registry(self):
        if self._registry is None:
            self._registry = _load_registry_module().Registry()
        return self._registry

    def limit_for(self, request_data):
        """None to pass through; otherwise the reasoning-character limit, or 0 when
        the request replays no reasoning and only the empty-completion retry applies."""
        limit = self.registry.loop_guard_limit((request_data or {}).get("model"))
        if limit is None:
            return None
        return limit if _replayed_reasoning(request_data) else 0

    async def async_post_call_streaming_iterator_hook(self, user_api_key_dict, response, request_data):
        limit = self.limit_for(request_data)
        if limit is None:
            async for chunk in response:
                yield chunk
            return

        held, chars, why = [], 0, None
        async for chunk in response:
            if held is None:
                yield chunk
                continue
            t = _event_type(chunk)
            held.append(chunk)
            if _is_reasoning_delta(t):
                chars += len(_get(chunk, "delta") or "")
            if _is_answer(chunk, t):
                for h in held:
                    yield h
                held = None
                continue
            if limit and chars > limit:
                why = "threshold"
                break
            if t == "response.incomplete" and limit:
                why = "incomplete"
                break
            if t == "response.completed":
                why = "empty"
                break

        if why is None:
            for h in held or []:
                yield h
            return

        close = getattr(response, "aclose", None)
        if close is not None:
            try:
                await close()
            except Exception:  # noqa: BLE001 - the abandoned stream's cleanup is best effort
                pass
        if why == "empty":
            retry = resend(request_data, drop_reasoning=False)
            log.warning("reasoning_loop_guard: completed with no answer or tool call after "
                        "%d reasoning chars; retrying once unchanged", chars)
        else:
            retry = resend(request_data)
            log.warning("reasoning_loop_guard: %s after %d reasoning chars; retrying once "
                        "without %d replayed reasoning item(s)", why, chars,
                        _replayed_reasoning(request_data))
        async for chunk in await self._retry(retry):
            yield chunk


proxy_handler_instance = ReasoningLoopGuard()
