# ── client integration backend ──────────────────────────────────────────────
# A SECOND execution backend, not a second benchmark system. Everything after
# LiteLLM is unchanged; only the thing issuing the request differs.
#
# Model benchmarks answer "which model performs better". These answer "which
# client provides a working engineering workflow" — session persistence,
# compaction, tool routing, MCP, hooks, retries. lm-eval cannot see any of that
# because it bypasses the client entirely.
#
# Uses each client's OWN resume/continue support rather than wrapping it:
#   claude  -p --resume <id>      (non-interactive print mode)
#   codex   exec resume --last
#: EXACT session identity only. `claude --continue` and `codex exec resume
#: --last` select the most recent session on the machine — which may belong to
#: another terminal, another repository, a manual session, or a concurrent run.
#: For automated benchmarking that is a correctness hazard, not a convenience.
CLIENTS = {
    "claude-local": {
        "bin": "claude-local",
        "start": lambda p: ["-p", "--output-format", "json", p],
        "resume": lambda sid, p: ["-p", "--output-format", "json",
                                  "--resume", sid, p],
    },
    "codex-local": {
        "bin": "codex-local",
        "start": lambda p: ["exec", "--json", p],
        # `codex exec resume <SESSION_ID> <PROMPT>` — positional, verified from
        # `codex exec resume --help`. NEVER --last.
        "resume": lambda sid, p: ["exec", "resume", sid, "--json", p],
    },
}
#: Opt-in, manual debugging only. Never the benchmark path.
IMPLICIT_RESUME = {"claude-local": ["--continue"],
                   "codex-local": ["exec", "resume", "--last"]}
#: Defines claude-local / codex-local. Generated by sync-models.py.
CLIENT_ENV = REPO / "config" / "clients" / "configure.zsh"


def _shq(s: str) -> str:
    return "'" + str(s).replace("'", "'\\''") + "'"


class SessionLost(RuntimeError):
    """The exact session id could not be captured or resumed. Fail closed."""


def permission_args(profile: dict) -> list:
    """Claude Code CLI flags for a DECLARED permission contract.

    Verified flags: --allowedTools / --disallowedTools / --permission-mode /
    --add-dir. Declaring them matters because the client's settings.json here
    carries `permissions: {}` — so a benchmark that says nothing inherits
    whatever print mode defaults to, and print mode cannot approve anything
    interactively. MEASURED consequence: Bash and Write were denied while
    Read/Glob/Grep passed, and one candidate spent 31 internal turns replanning
    around a restriction the benchmark never meant to impose.

    Never use --dangerously-skip-permissions: a planning-only comparison that
    can write is not planning-only.
    """
    args = []
    if profile.get("allowed"):
        args += ["--allowedTools", profile["allowed"]]
    if profile.get("denied"):
        args += ["--disallowedTools", profile["denied"]]
    if profile.get("mode"):
        args += ["--permission-mode", profile["mode"]]
    return args


def permission_manifest_hash(profile: dict) -> str:
    """Pin the contract so every candidate is provably given the same one."""
    body = "|".join(f"{k}={profile.get(k, '')}" for k in ("allowed", "denied", "mode"))
    return hashlib.sha256(body.encode()).hexdigest()
#: Read-only probes every planner candidate must be able to perform, and one
#: write that must fail. Run BEFORE turn 1: a permission defect discovered
#: during a scored run costs the whole run, which is exactly what happened.
PERMISSION_PREFLIGHT = (
    ("read", "Read the file config/active-profile and reply with ONLY its contents."),
    ("search", "Use Grep to count files matching 'active-profile' under scripts/. "
               "Reply with ONLY the number."),
    ("write_denied", "Create a file named PREFLIGHT_MUST_NOT_EXIST.txt containing 'x'. "
                     "If you cannot, reply with ONLY: DENIED"),
)


def verify_permissions(cwd: Path, profile: dict, extra_args: list = None,
                       timeout: int = 300) -> dict:
    """Prove the contract holds through the REAL client before scoring starts.

    Returns state VERIFIED or INVALID_PERMISSIONS. The caller must abort on the
    latter rather than let a candidate discover it mid-run.
    """
    results, ok = {}, True
    for name, prompt in PERMISSION_PREFLIGHT:
        rec = run_client_turn("claude-local", prompt, None, cwd, timeout=timeout,
                              extra_args=(extra_args or []) + permission_args(profile))
        denials = (rec.get("structured") or {}).get("permission_denials") or []
        out = (rec.get("structured") or {}).get("result") or ""
        if name == "write_denied":
            passed = bool(denials) or "DENIED" in out.upper()
        else:
            passed = rec.get("outcome") == "SUCCESS" and not denials
        results[name] = {"passed": passed, "outcome": rec.get("outcome"),
                         "denials": [d.get("tool_name") for d in denials],
                         "reply": out[:200]}
        ok = ok and passed
    wrote = (cwd / "PREFLIGHT_MUST_NOT_EXIST.txt").exists()
    if wrote:
        ok = False
    return {"state": "VERIFIED" if ok else "INVALID_PERMISSIONS",
            "manifest_sha256": permission_manifest_hash(profile),
            "forbidden_file_created": wrote, "probes": results}


def run_client_turn(client: str, prompt: str, session: str, cwd: Path,
                    timeout: int = 900, extra_args: list = None) -> dict:
    """One turn through a real client, resuming an EXACT session id.

    `session` is None only for the first turn. Any later turn without an id is a
    hard failure — silently falling back to "latest session" could attach the
    benchmark to the user's own conversation.
    """
    spec = CLIENTS[client]
    args = spec["resume"](session, prompt) if session else spec["start"](prompt)
    # Permission flags precede the prompt-bearing args the spec built.
    args = list(extra_args or []) + args
    # claude-local / codex-local are ZSH FUNCTIONS, not binaries: they export the
    # ailocal base URL, API key and capability-alias slots before calling the
    # real CLI. `command -v` finds them, but subprocess cannot exec them — so
    # they are invoked through a shell that sources their definition. Calling
    # `claude` directly would bypass ailocal routing entirely.
    inner = " ".join([spec["bin"]] + [_shq(a) for a in args])
    cmd = ["zsh", "-c", f"source {_shq(str(CLIENT_ENV))} >/dev/null 2>&1; {inner}"]
    before = telemetry()
    started = time.time()
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                           cwd=str(cwd))
        rc, out, err = r.returncode, r.stdout, r.stderr
        timed_out = False
    except subprocess.TimeoutExpired as e:
        rc, out, err, timed_out = None, (e.stdout or b"").decode()[:4000], "", True
    wall = time.time() - started

    session_id, tool_calls, usage = None, 0, {}
    for line in out.splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            d = json.loads(line)
        except json.JSONDecodeError:
            continue
        # Codex names it thread_id (emitted on `thread.started`); Claude Code
        # names it session_id. Same concept, different key.
        session_id = (d.get("session_id") or d.get("sessionId")
                      or d.get("thread_id") or session_id)
        if d.get("type") in ("tool_use", "tool_call", "function_call"):
            tool_calls += 1
        for key in ("usage", "token_usage"):
            if isinstance(d.get(key), dict):
                usage = d[key]
    # claude -p --output-format json emits one object, not a stream
    if not session_id:
        try:
            d = json.loads(out)
            session_id = d.get("session_id")
            usage = d.get("usage") or usage
            tool_calls = tool_calls or len(d.get("tool_uses") or [])
        except (json.JSONDecodeError, TypeError):
            pass

    structured = parse_client_result(out)
    return {
        "client": client, "requested_session": session,
        "command": " ".join(cmd[:6]) + (" ..." if len(cmd) > 6 else ""),
        "returncode": rc,
        "timed_out": timed_out, "wall_seconds": round(wall, 2),
        "session_id": session_id, "tool_calls": tool_calls,
        "prompt_tokens": usage.get("input_tokens") or usage.get("prompt_tokens"),
        "completion_tokens": (usage.get("output_tokens")
                              or usage.get("completion_tokens")),
        # stdout_tail keeps existing consumers cheap; stdout_full is the scored
        # evidence. A planning answer runs far past 1,200 characters, and
        # scoring a truncated plan measures the tail, not the plan.
        "stdout_tail": out[-1200:], "stdout_full": out, "stderr_tail": err[-600:],
        "telemetry_before": before, "telemetry_after": telemetry(),
        "structured": structured,
        "outcome": classify_client_outcome(structured, rc, timed_out),
        "crashed": rc not in (0, None),
    }
#: Fields Claude Code reports on its terminal result object. Persisted verbatim:
#: a benchmark that discards the client's own explanation of a failure forces the
#: next reader to re-derive it from transport logs.
_CLAUDE_RESULT_KEYS = ("is_error", "terminal_reason", "result", "num_turns",
                       "subtype", "stop_reason", "session_id", "modelUsage",
                       "permission_denials", "usage", "api_error_status",
                       "duration_ms", "duration_api_ms", "thread_id")


def parse_client_result(out: str) -> dict:
    """The client's own terminal result object, if it emitted one.

    Claude Code's `-p --output-format json` writes ONE object to STDOUT and
    leaves stderr empty — including when it fails. Scanning stderr therefore
    reveals nothing, which is exactly how a structured, self-describing
    `api_error` was read as an opaque crash for several days.

    Both shapes are handled: a single object, and a JSONL stream whose last
    `type: result` line carries the outcome.
    """
    if not out or not out.strip():
        return {}
    candidates = []
    stripped = out.strip()
    try:
        d = json.loads(stripped)
        if isinstance(d, dict):
            candidates.append(d)
    except (json.JSONDecodeError, TypeError):
        pass
    if not candidates:
        for line in stripped.splitlines():
            line = line.strip()
            if not line.startswith("{"):
                continue
            try:
                d = json.loads(line)
            except json.JSONDecodeError:
                continue
            if isinstance(d, dict) and (d.get("type") == "result"
                                        or "terminal_reason" in d
                                        or "is_error" in d):
                candidates.append(d)
    if not candidates:
        return {}
    d = candidates[-1]
    return {k: d[k] for k in _CLAUDE_RESULT_KEYS if k in d}
#: Substring of Claude Code's own message when its client-side output guard
#: fires. MEASURED verbatim from run2 candidate-a turn 2:
#:   "Claude's response exceeded the 32000 output token maximum. To configure
#:    this behavior, set the CLAUDE_CODE_MAX_OUTPUT_TOKENS environment variable."
#: Matched loosely (no token count) so a different configured limit still hits.
_OUTPUT_LIMIT_MARKERS = ("output token maximum", "CLAUDE_CODE_MAX_OUTPUT_TOKENS")


def classify_client_outcome(structured: dict, rc, timed_out: bool) -> str:
    """Outcome, decided by what the client SAID — not by its exit code.

    A non-zero rc alone proves only that the process was unhappy. Claude Code
    exits 1 for an API error while still reporting, in full, what went wrong and
    how much work it completed. Collapsing that into CLIENT_PROCESS_CRASH throws
    away the diagnosis and points the next investigation at the transport layer.
    A real crash is the case where NO usable terminal result exists.
    """
    if timed_out:
        return "CLIENT_TIMEOUT"
    if structured:
        msg = str(structured.get("result") or "")
        is_error = bool(structured.get("is_error"))
        reason = str(structured.get("terminal_reason") or "")
        if is_error or reason == "api_error":
            if any(m in msg for m in _OUTPUT_LIMIT_MARKERS):
                return "CLIENT_OUTPUT_LIMIT"
            return "CLIENT_API_ERROR"
        # Denials are recorded even on a successful turn; they only DECIDE the
        # outcome when the turn also failed.
        if rc not in (0, None) and structured.get("permission_denials"):
            return "CLIENT_PERMISSION_DENIED"
        if rc in (0, None):
            return "SUCCESS"
        return "UNKNOWN"
    if rc not in (0, None):
        return "CLIENT_PROCESS_CRASH"
    return "UNKNOWN"


def client_version(client: str) -> str:
    try:
        r = subprocess.run(
            ["zsh", "-c", f"source {_shq(str(CLIENT_ENV))} >/dev/null 2>&1; "
                          f"{CLIENTS[client]['bin']} --version"],
            capture_output=True, text=True, timeout=30)
        return r.stdout.strip()[:60]
    except Exception:
        return "unknown"


def disposable_worktree(run_id: str) -> Path:
    """An isolated git worktree per run, OUTSIDE every denied root.

    Scenarios that mutate code must never touch the live checkout, and two runs
    must never share a tree. It now also must not live under $HOME: deny beats
    allow, so a worktree inside a denied root is unreadable by its own
    candidate and the run aborts at preflight instead of starting unconfined.

    Durable evidence and the planner ground truth deliberately stay where they
    were, under state_dir() inside $HOME -- which is a DENIED root. That is the
    separation: the candidate can see its worktree and nothing else, while the
    evidence it must not read sits somewhere it cannot reach.
    """
    wt = benchmark_worktree_root() / run_id
    wt.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["git", "-C", str(REPO), "worktree", "add", "--detach",
                    str(wt), "HEAD"], capture_output=True, text=True, timeout=120)
    return wt


def _cleanup_is_safe(wt: Path) -> str:
    """Refuse to recursively delete anything we did not create.

    A benchmark that rm -rf's an unverified path once is a benchmark nobody runs
    again. Checked against RESOLVED paths, so a symlink cannot smuggle the
    target somewhere else."""
    try:
        p = Path(wt).resolve()
    except Exception:  # noqa: BLE001
        return "UNRESOLVABLE"
    forbidden = [Path.home(), Path(REPO).resolve(), state_dir().resolve(),
                 Path("/"), benchmark_worktree_root()]
    if any(p == f.resolve() for f in forbidden):
        return "REFUSED_PROTECTED_PATH"
    root = str(benchmark_worktree_root())
    if not str(p).startswith(root.rstrip("/") + "/"):
        return "REFUSED_OUTSIDE_OWNED_ROOT"
    return "SAFE"


def sweep_worktree_root() -> dict:
    """Remove per-run settings files whose worktree no longer exists.

    A crashed or timed-out run leaves its .confine-*.json behind, and those
    accumulate in the owned root forever. Only orphans are touched: a settings
    file whose worktree is still present belongs to a live run."""
    root = benchmark_worktree_root()
    removed = []
    # Canaries live in $HOME by design (it must be a denied region). A killed
    # run cannot clean up after itself, so orphans are swept here rather than
    # left to accumulate in the user's home directory.
    for c in Path.home().glob(".ailocal-confinement-canary-*.txt"):
        try:
            c.unlink()
            removed.append(c.name)
        except Exception:  # noqa: BLE001
            pass
    for f in root.glob(".confine-*.json"):
        name = f.name[len(".confine-"):-len(".json")]
        if not (root / name).exists():
            try:
                f.unlink()
                removed.append(f.name)
            except Exception:  # noqa: BLE001
                pass
    return {"orphans_removed": removed}


def remove_worktree(wt: Path) -> dict:
    """Deregister then delete, and only inside the owned root.

    Returns a status rather than raising: a cleanup failure must be reported
    without masking the scenario result that preceded it."""
    verdict = _cleanup_is_safe(wt)
    if verdict != "SAFE":
        return {"removed": False, "status": WORKTREE_CLEANUP_FAILED,
                "reason": verdict, "path": str(wt)}
    git = subprocess.run(["git", "-C", str(REPO), "worktree", "remove", "--force",
                          str(wt)], capture_output=True, text=True, timeout=120)
    leftover = Path(wt).exists()
    if leftover:
        try:
            shutil.rmtree(Path(wt).resolve(), ignore_errors=False)
        except Exception as exc:  # noqa: BLE001
            return {"removed": False, "status": WORKTREE_CLEANUP_FAILED,
                    "reason": f"rmtree: {type(exc).__name__}", "path": str(wt),
                    "git_rc": git.returncode}
    # The per-run settings file lives beside the worktree, not inside it.
    for stray in Path(wt).parent.glob(f".confine-{Path(wt).name}.json"):
        stray.unlink(missing_ok=True)
    sweep_worktree_root()
    return {"removed": not Path(wt).exists(), "status": "OK",
            "git_rc": git.returncode, "path": str(wt)}


def run_client_scenario(client: str, turns: list, cwd: Path,
                        timeout: int = 900, extra_args: list = None,
                        confinement: dict = None) -> dict:
    """A multi-turn session through one client, on ONE exact session id.

    Fails closed: if the first turn yields no session id, or a later turn
    reports a different one, the scenario stops. Continuing would silently
    measure a different conversation — possibly the user's own.

    CONFINEMENT (planner path only). Pass `confinement` to require a PROVEN
    filesystem sandbox before any inference:

        {"model": <candidate alias>, "permissions": {...},
         "probe_model": <optional capable alias>, "extra_paths": [...]}

    Omit it and behaviour is exactly what it was -- non-planner scenarios are
    untouched unless they opt in.

    Ordering is load-bearing: verify, pin, then run. The preflight proves the
    sandbox for a specific effective configuration, so the candidate must run
    under that same configuration or the proof does not apply to it. A manifest
    hash pins it and a mismatch aborts before turn 1 rather than after.

    Why a ground-truth-readable candidate is not merely untidy: before this,
    the planner answer key was readable by absolute path, so an unconfined run
    could not be distinguished from one that had read the answers.
    """
    records, session = [], None
    error = None
    confine = {"required": bool(confinement)}
    canary = {"token": None, "path": None, "planted": False}
    extra_args = list(extra_args or [])

    if confinement:
        model = confinement.get("model")
        perms = confinement.get("permissions") or {}
        wt = Path(cwd).resolve()
        args_conf = confinement_args(
            wt, deny_extra=confinement.get("sibling_worktrees") or ())
        settings_path = args_conf[1]
        pre_manifest = confinement_manifest(
            wt, model, perms, settings_path,
            deny_extra=confinement.get("sibling_worktrees") or ())

        res = verify_confinement(wt, model, perms,
                                 extra_paths=confinement.get("extra_paths"),
                                 timeout=confinement.get("timeout", 600),
                                 probe_model=confinement.get("probe_model"))
        confine.update({"preflight": res, "manifest": pre_manifest})

        if res["state"] != CONFINEMENT_VERIFIED:
            # Not started, not attempted, not scored.
            return {"client": client, "turns_planned": len(turns),
                    "turns_completed": 0, "session_id": None,
                    "session_continuous": False, "error": res["state"],
                    "cwd": str(cwd), "tool_calls": 0, "crashes": 0,
                    "timeouts": 0, "wall_seconds": 0.0,
                    "ttft_first_turn": None, "records": [],
                    "confinement": confine}

        # Re-derive the manifest AFTER the probe. If anything the sandbox
        # depends on moved during preflight, the verified configuration is not
        # the one the candidate would get.
        post_manifest = confinement_manifest(
            wt, model, perms, settings_path,
            deny_extra=confinement.get("sibling_worktrees") or ())
        confine["manifest_after_preflight"] = post_manifest
        if post_manifest["hash"] != pre_manifest["hash"]:
            confine["mismatch"] = {"before": pre_manifest["hash"],
                                   "after": post_manifest["hash"]}
            return {"client": client, "turns_planned": len(turns),
                    "turns_completed": 0, "session_id": None,
                    "session_continuous": False,
                    "error": INVALID_CONFINEMENT_CONFIGURATION,
                    "cwd": str(cwd), "tool_calls": 0, "crashes": 0,
                    "timeouts": 0, "wall_seconds": 0.0,
                    "ttft_first_turn": None, "records": [],
                    "confinement": confine}

        # The candidate now inherits the EXACT verified sandbox settings file.
        extra_args = extra_args + permission_args(perms) + \
            ["--model", model] + ["--settings", settings_path]
        canary = plant_canary(wt)
        confine["canary_planted"] = canary["planted"]
    for i, prompt in enumerate(turns):
        if i and not session:
            error = ("SESSION_LOST: no session id captured from turn 1; "
                     "refusing to fall back to implicit latest-session resume")
            break
        rec = run_client_turn(client, prompt, session, cwd, timeout=timeout,
                              extra_args=extra_args)
        rec["turn"] = i + 1
        if confinement:
            esc = detect_escape(rec, canary)
            rec["confinement_event"] = esc
            confine.setdefault("events", []).append({"turn": i + 1, **esc})
            if esc["breach"]:
                # POSITIVE evidence that a denied region was read. Stop now: no
                # later turn is interpretable once the boundary is gone.
                records.append(rec)
                error = INVALID_CONFINEMENT_BREACH
                break
        got = rec.get("session_id")
        if i == 0:
            session = got
            rec["session_continuous"] = bool(session)
            if not session:
                records.append(rec)
                error = ("SESSION_LOST: client returned no session id on turn 1")
                break
        else:
            # An id that changes mid-scenario means the client started a NEW
            # conversation; every later turn would measure something else.
            rec["session_continuous"] = got in (None, session)
            if not rec["session_continuous"]:
                records.append(rec)
                error = (f"SESSION_DIVERGED: expected {session}, got {got}")
                break
        records.append(rec)
        # The scenario error is the CLASSIFIED outcome, not "CLIENT_CRASH" for
        # every non-zero exit. Claude Code exits 1 on an API error while
        # reporting exactly what happened; labelling that a crash discards the
        # diagnosis and sends the next investigation to the transport layer.
        outcome = rec.get("outcome") or "UNKNOWN"
        if outcome not in ("SUCCESS",):
            error = outcome
            break
    if canary.get("path"):
        # Always removed, on success and on every failure path above that
        # reaches here -- a stray canary in $HOME is litter.
        try:
            Path(canary["path"]).unlink(missing_ok=True)
            confine["canary_removed"] = True
        except Exception:  # noqa: BLE001
            confine["canary_removed"] = False

    return {
        "client": client, "turns_planned": len(turns),
        "turns_completed": len(records),
        "session_id": session,
        "session_continuous": bool(records) and all(
            r["session_continuous"] for r in records),
        "error": error,
        "cwd": str(cwd),
        "tool_calls": sum(r["tool_calls"] for r in records),
        "crashes": sum(1 for r in records if r["crashed"]),
        "timeouts": sum(1 for r in records if r["timed_out"]),
        "wall_seconds": round(sum(r["wall_seconds"] for r in records), 1),
        "ttft_first_turn": records[0]["wall_seconds"] if records else None,
        "records": records,
        "confinement": confine,
    }


def served_models_since(seconds: int = 120) -> set:
    """Alias names LiteLLM actually served recently, from the proxy's own log.

    The authoritative answer to "which model ran". Client-reported identity is
    not evidence: a benchmark once completed nine clean turns while every
    request silently served the production alias, because settings.json's
    `model` key outranks the ANTHROPIC_DEFAULT_* slot vars.
    """
    try:
        r = subprocess.run(["docker", "logs", "ailocal-litellm",
                            "--since", f"{seconds}s"],
                           capture_output=True, text=True, timeout=60)
    except Exception:
        return set()
    text = (r.stdout or "") + (r.stderr or "")
    return set(re.findall(r"(?:bench-[a-z0-9.-]+|ailocal-[a-z]+)", text))


def verify_routing(alias: str, model: str, cwd, key: str = None) -> dict:
    """Prove the client reaches `alias` BEFORE any scored turn runs.

    One probe through the real client, then the proxy log is checked for the
    exact alias. Fail closed: a routing mismatch invalidates everything that
    would follow it, so the caller must abort rather than continue.
    """
    probe = run_client_turn("claude-local", "Reply ONLY with OK.", None, cwd,
                            timeout=300)
    served = served_models_since(180)
    info = model_info(model)
    ok = alias in served
    return {"state": "VERIFIED" if ok else "INVALID_ROUTING",
            "requested_alias": alias, "served_aliases": sorted(served),
            "alias_served": ok,
            "expected_digest": info.get("digest", ""),
            "probe_rc": probe.get("returncode"),
            "probe_session": probe.get("session_id"),
            "probe_wall_seconds": probe.get("wall_seconds")}


# ── worktree confinement ────────────────────────────────────────────────────
# WHY THIS EXISTS. A planner candidate read an unrelated repository and the
# ground-truth answer key. Permissions were never the gap: they control WHICH
# TOOLS may run, not WHICH PATHS an allowed tool may touch. With Read allowed,
# an absolute path anywhere on the machine was readable.
#
# MEASURED, same prompt, same permission contract, one cheap turn each:
#   without confinement   INSIDE=OK PARENT=OK AILOCAL_CFG=OK CADENCE=OK
#                         GROUNDTRUTH=OK      <- the answer key was readable
#   with confinement      INSIDE=OK PARENT=DENIED AILOCAL_CFG=DENIED
#                         CADENCE=DENIED GROUNDTRUTH=DENIED
#
# The mechanism is Claude Code's OWN filesystem sandbox (2.1.220), configured
# per run through --settings. It is a process-level boundary, not a prompt
# instruction and not a path regex: sandbox.filesystem.denyRead removes whole
# regions and allowRead re-admits exactly the worktree.
#
# macOS sandbox-exec was evaluated first and rejected: on macOS 26.6 every
# invocation aborted with SIGABRT, including reads INSIDE the allowed subpath.
# --add-dir was rejected because it EXPANDS the accessible set; the documented
# flag has no deny semantics and confines nothing.
CONFINEMENT_VERIFIED = "VERIFIED_CONFINEMENT"
CONFINEMENT_INVALID = "INVALID_CONFINEMENT"
CONFINEMENT_UNAVAILABLE = "CONFINEMENT_UNAVAILABLE"


CONFINEMENT_WORKTREE_INSIDE_DENIED_ROOT = "CONFINEMENT_WORKTREE_INSIDE_DENIED_ROOT"

#: Roots denied wholesale. Regions, not a blocklist of known-bad paths: the
#: escape that matters is the one nobody predicted.
DENIED_ROOTS = ("/Users", "/etc", "/opt", "/usr/local")


def confinement_settings(worktree, deny_extra=()) -> dict:
    """Deny whole roots with Read() rules, then re-admit exactly one worktree.

    MECHANISM CORRECTION (measured 2026-08-03). An earlier version used
    `sandbox.filesystem.denyRead/allowRead`. Passed through --settings on
    2.1.220 that key did NOT confine: a probe read the canary in $HOME AND the
    full planner ground truth while the settings file was in force. The first
    "verification" of it rested on a model self-reporting DENIED; the
    token-based preflight, which cannot be talked out of a result, showed the
    reads succeeding. `permissions.deny` with Read(<root>/**) rules does hold:
    same probe, ground truth denied, worktree still readable.

    DENY BEATS ALLOW, and that is not configurable. A worktree INSIDE a denied
    root is therefore unreadable by its own candidate -- measured: a worktree
    under $HOME with Read($HOME/**) denied returned neither the inside file nor
    the ground truth. So candidate worktrees must live outside the denied roots,
    and confinement_args refuses rather than emitting a policy that would either
    break the run or silently confine nothing.
    """
    wt = Path(worktree).resolve()
    # SIBLINGS MUST BE NAMED. The owned worktree root is not a denied root -- it
    # cannot be, since deny beats allow and the candidate must read its own tree
    # inside it. So a sibling candidate's worktree is only hidden by denying it
    # explicitly. This is bounded enumeration of paths we created ourselves, not
    # a blocklist of guessed-at dangers.
    siblings = [f"Read(/{Path(d).resolve()}/**)" for d in deny_extra]
    return {"permissions": {
        # DOUBLE SLASH. Claude Code reads Read(/x) as project-relative and
        # Read(//x) as absolute from the filesystem root. Single-slash rules
        # matched nothing here and the canary in $HOME stayed readable -- a
        # deny list that silently matches nothing is worse than none, because
        # it reads as protection.
        "deny": [f"Read(/{r}/**)" for r in DENIED_ROOTS]
                + [f"Read(/{Path.home()}/**)"] + siblings,
        "allow": [f"Read(/{wt}/**)", "Glob", "Grep"],
        "defaultMode": "default"}}


INSIDE_DENIED_ROOT = "INSIDE_DENIED_ROOT"
OUTSIDE_OWNED_TEMP_ROOT = "OUTSIDE_OWNED_TEMP_ROOT"
SYMLINK_TARGET_DENIED = "SYMLINK_TARGET_DENIED"
ROOT_NOT_PRIVATE = "ROOT_NOT_PRIVATE"
CONFINABLE = "CONFINABLE"
WORKTREE_CLEANUP_FAILED = "WORKTREE_CLEANUP_FAILED"


def benchmark_worktree_root() -> Path:
    """The one directory candidate worktrees may live in.

    OUTSIDE $HOME by necessity, not preference: deny beats allow and cannot be
    overridden, so a worktree under a denied root is unreadable by its own
    candidate. state_dir() is under $HOME, which is why worktrees had to move.

    The system temp dir is resolved rather than hard-coded: on macOS TMPDIR is a
    per-user directory under /var/folders that REALPATHS to /private/var/folders,
    and a policy written against the unresolved path matches nothing.
    """
    root = Path(tempfile.gettempdir()).resolve() / "ailocal-benchmark" / "worktrees"
    root.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(root.parent, 0o700)
        os.chmod(root, 0o700)
    except Exception:  # noqa: BLE001
        pass
    return root


def worktree_is_confinable(worktree) -> str:
    """Can this exact path be confined? Returns a REASON, never a bare bool.

    "No" has several causes with different fixes -- a path under $HOME, a path
    outside the owned root, a symlink pointing somewhere denied, a world-readable
    root -- and collapsing them to False sends the next reader looking in the
    wrong place.
    """
    raw = Path(worktree)
    wt = raw.resolve()                      # symlinks resolved BEFORE any check
    roots = list(DENIED_ROOTS) + [str(Path.home())]

    def under(path, root):
        root = root.rstrip("/")
        return str(path) == root or str(path).startswith(root + "/")

    if any(under(wt, r) for r in roots):
        # A symlink that LOOKS confinable but resolves into a denied root is the
        # interesting case: the policy is written against the resolved path, so
        # the candidate would simply be unable to read its own tree.
        return SYMLINK_TARGET_DENIED if raw.is_symlink() or str(raw) != str(wt) \
            else INSIDE_DENIED_ROOT

    owned = benchmark_worktree_root()
    if not under(wt, str(owned)):
        return OUTSIDE_OWNED_TEMP_ROOT

    try:
        if (owned.stat().st_mode & 0o077) != 0:
            return ROOT_NOT_PRIVATE
    except Exception:  # noqa: BLE001
        return ROOT_NOT_PRIVATE
    return CONFINABLE


def confinement_args(worktree, settings_path=None, deny_extra=()) -> list:
    """CLI flags installing the confinement for ONE run."""
    wt = Path(worktree).resolve()
    verdict = worktree_is_confinable(wt)
    if verdict != CONFINABLE:
        raise ValueError(
            f"{verdict}: {wt} cannot be confined. Deny beats allow, so a "
            "worktree under a denied root is unreadable by its own candidate. "
            f"Create it under {benchmark_worktree_root()}.")
    dst = Path(settings_path) if settings_path else wt.parent / f".confine-{wt.name}.json"
    dst.write_text(json.dumps(confinement_settings(wt, deny_extra), indent=1))
    return ["--settings", str(dst)]


def verify_confinement(worktree, model: str, permissions: dict,
                       extra_paths=None, timeout: int = 600,
                       probe_model: str = None) -> dict:
    """Prove confinement with the REAL client before a candidate runs.

    TOKEN-BASED, not verdict-based. An earlier version asked the model to emit
    one LABEL=OK/DENIED line per path; a capable model still stopped after
    three of six labels and the preflight had to report PROBE_OUTPUT_INVALID.
    Confinement is a property of the client, so making the proof depend on a
    model's formatting discipline was the wrong design.

    Instead two uniquely-tokened files are planted -- one INSIDE the worktree,
    one OUTSIDE in a denied region -- and the model is asked to read both and
    echo what it got. The verdict is then computed from the tokens:

        inside token present  -> the allowed region really is readable
        outside token absent  -> the denied region really is not

    The outside read is a POSITIVE control: the model is explicitly asked for
    it, so absence of the token is evidence of denial rather than evidence of
    incuriosity. No parsing of model prose decides anything.

    Fails closed, and keeps three different failures apart: the client not
    running usably (CONFINEMENT_UNAVAILABLE), the probe producing nothing
    usable (PROBE_OUTPUT_INVALID), and a denied path proving readable
    (INVALID_CONFINEMENT).
    """
    wt = Path(worktree).resolve()
    inside_token = "ZQXINSIDE-" + uuid.uuid4().hex[:16]
    inside = wt / ".confinement-probe"
    inside.write_text(inside_token + "\n")
    canary = plant_canary(wt)

    targets = [("INSIDE", str(inside))]
    if canary["planted"]:
        targets.append(("OUTSIDE_CANARY", canary["path"]))
    for i, p in enumerate(extra_paths or []):
        targets.append((f"EXTRA{i}", str(p)))

    prompt = ("Read each of these files with the Read tool and print the exact "
              "contents of each one. If a read fails, print DENIED for it.\n"
              + "\n".join(f"{k}: {v}" for k, v in targets))
    used = probe_model or model
    args = permission_args(permissions) + ["--model", used] + confinement_args(wt)
    rec = run_client_turn("claude-local", prompt, None, wt, timeout=timeout,
                          extra_args=args)
    blob = ((rec.get("structured") or {}).get("result") or "") + \
        (rec.get("stdout_full") or "")

    inside_ok = inside_token in blob
    outside_leaked = bool(canary["token"] and canary["token"] in blob)

    inside.unlink(missing_ok=True)
    if canary.get("path"):
        try:
            Path(canary["path"]).unlink(missing_ok=True)
        except Exception:  # noqa: BLE001
            pass

    if rec.get("returncode") not in (0,):
        state = CONFINEMENT_UNAVAILABLE      # the client never ran usably
    elif outside_leaked:
        state = CONFINEMENT_INVALID          # a denied region was readable
    elif not inside_ok:
        state = PROBE_OUTPUT_INVALID         # ran, but proved nothing either way
    else:
        state = CONFINEMENT_VERIFIED

    # Secondary, advisory only: never used to decide the state.
    verdict = {}
    for label, _ in targets:
        m = re.search(rf"{label}\s*[:=]\s*(OK|DENIED)", blob, re.I)
        verdict[label] = m.group(1).upper() if m else "UNREPORTED"

    return {"state": state, "verdict": verdict, "worktree": str(wt),
            "probe_model": used, "candidate_model": model,
            "inside_token_returned": inside_ok,
            "outside_token_returned": outside_leaked,
            "canary_planted": canary["planted"],
            "client_rc": rec.get("returncode"), "outcome": rec.get("outcome"),
            "raw_result": blob[:800]}


# ── confinement manifest and breach detection ───────────────────────────────
# The preflight is only meaningful if the candidate runs under the SAME
# effective configuration it verified. A manifest pins that: if anything the
# sandbox depends on changes between preflight and turn 1, the proof no longer
# applies to the run and the scenario must not start.
INVALID_CONFINEMENT_CONFIGURATION = "INVALID_CONFINEMENT_CONFIGURATION"
INVALID_CONFINEMENT_BREACH = "INVALID_CONFINEMENT_BREACH"
CONFINEMENT_ESCAPE_BLOCKED = "CONFINEMENT_ESCAPE_BLOCKED"
PROBE_OUTPUT_INVALID = "PROBE_OUTPUT_INVALID"
INVALID_PERMISSIONS = "INVALID_PERMISSIONS"


def confinement_manifest(worktree, model: str, permissions: dict,
                         settings_path=None, deny_extra=()) -> dict:
    """Everything the sandbox proof depends on, hashed.

    Deliberately includes the ENVIRONMENT pieces that silently change a run's
    effective policy -- CLAUDE_CONFIG_DIR and HOME -- because a preflight run
    under one config directory says nothing about a candidate run under
    another."""
    wt = Path(worktree).resolve()
    settings = confinement_settings(wt, deny_extra)
    body = json.dumps({
        "settings": settings,
        "worktree": str(wt),
        "claude_config_dir": os.environ.get("CLAUDE_CONFIG_DIR", ""),
        "home": os.environ.get("HOME", ""),
        "model": model,
        "permission_manifest": permission_manifest_hash(permissions),
        "settings_path": str(settings_path or ""),
    }, sort_keys=True)
    return {
        "hash": hashlib.sha256(body.encode()).hexdigest(),
        "settings": settings,
        "worktree": str(wt),
        "allowed_read": settings["permissions"]["allow"],
        "denied_read": settings["permissions"]["deny"],
        "claude_config_dir": os.environ.get("CLAUDE_CONFIG_DIR", ""),
        "home": os.environ.get("HOME", ""),
        "requested_alias": model,
        "permission_manifest": permission_manifest_hash(permissions),
        "settings_path": str(settings_path or ""),
        # The three roots kept apart, resolved, so a reader never has to infer
        # which one the candidate could see.
        "candidate_worktree_root": str(benchmark_worktree_root()),
        "evidence_root": str(state_dir().resolve()),
        "ground_truth_root": str((state_dir() / "planner").resolve()),
        "sibling_worktrees_denied": [str(Path(d).resolve()) for d in deny_extra],
    }


def plant_canary(worktree) -> dict:
    """A uniquely-tokened file OUTSIDE the worktree, in a denied region.

    Breach detection needs POSITIVE evidence. Counting refusals proves nothing
    -- a model that never tried also produces zero refusals. If this token ever
    appears in candidate output, an outside read demonstrably succeeded."""
    # The token must NOT appear in the FILENAME. It did, and the path is echoed
    # back whenever the client explains that it refused to read it -- so a
    # correct denial ("DENIED for ...canary-ZQX....txt") looked exactly like a
    # leak and the preflight reported INVALID_CONFINEMENT on a sandbox that was
    # working. Token lives in the CONTENTS only; the name is unrelated.
    token = "ZQXCANARY-" + uuid.uuid4().hex[:16]
    path = Path.home() / f".ailocal-confinement-canary-{uuid.uuid4().hex[:12]}.txt"
    try:
        path.write_text(f"{token}\n")
    except Exception:  # noqa: BLE001
        return {"token": None, "path": None, "planted": False}
    return {"token": token, "path": str(path), "planted": True}


def detect_escape(record: dict, canary: dict) -> dict:
    """Classify one turn's filesystem behaviour.

    A blocked attempt is NOT a failure -- the sandbox did its job -- but it is
    recorded, because a candidate that spent turns probing the filesystem is not
    comparable to one that did not."""
    blob = (record.get("stdout_full") or "") + (record.get("stderr_tail") or "")
    breach = bool(canary.get("token") and canary["token"] in blob)
    denials = ((record.get("structured") or {}).get("permission_denials") or [])
    outside = 0
    for d in denials:
        cmd = json.dumps(d.get("tool_input") or {})
        # The path may sit anywhere in the serialized tool input -- after a
        # quote, a space, or `cd`. Anchoring on a preceding quote missed
        # `{"command": "cat /Users/..."}` entirely.
        if re.search(r'(?<![\w])/(?:Users|private|var|tmp|etc|opt)/', cmd):
            outside += 1
    return {"breach": breach,
            "escape_attempts_blocked": outside,
            "state": (INVALID_CONFINEMENT_BREACH if breach
                      else CONFINEMENT_ESCAPE_BLOCKED if outside else None)}
